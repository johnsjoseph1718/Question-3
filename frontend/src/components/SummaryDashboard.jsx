import React, { useState } from 'react';
import {
  Globe,
  ExternalLink,
  Copy,
  Check,
  Download,
  RefreshCw,
  Target,
  Sparkles,
  Layers,
  Info,
  Users,
  Briefcase,
  Key,
  Compass,
  FileCheck2,
  Clock,
  BookOpen
} from 'lucide-react';
import SummaryCard from './SummaryCard';
import KeywordsCloud from './KeywordsCloud';
import AskWebsiteQA from './AskWebsiteQA';

export default function SummaryDashboard({ analysisData, onReset }) {
  const [copied, setCopied] = useState(false);

  const { metadata = {}, summary = {}, session_id } = analysisData;

  // Build clean text representation for clipboard & download
  const buildSummaryText = () => {
    const lines = [];
    lines.push(`=======================================================`);
    lines.push(`WEBINSIGHT - AI WEBSITE SUMMARY REPORT`);
    lines.push(`=======================================================`);
    lines.push(`Title:        ${metadata.title || 'N/A'}`);
    lines.push(`URL:          ${metadata.url || 'N/A'}`);
    lines.push(`Domain:       ${metadata.domain || 'N/A'}`);
    lines.push(`Words:        ${metadata.word_count || 0}`);
    lines.push(`Est. Reading: ${metadata.reading_time_minutes || 1} min(s)`);
    lines.push(`Generated:    ${new Date().toLocaleString()}`);
    lines.push(`-------------------------------------------------------`);
    lines.push(``);
    lines.push(`1. WEBSITE OVERVIEW`);
    lines.push(summary.website_overview || 'N/A');
    lines.push(``);
    lines.push(`2. MAIN PURPOSE`);
    lines.push(summary.main_purpose || 'N/A');
    lines.push(``);
    lines.push(`3. KEY FEATURES`);
    if (Array.isArray(summary.key_features)) {
      summary.key_features.forEach((f) => lines.push(`• ${f}`));
    } else {
      lines.push(summary.key_features || 'N/A');
    }
    lines.push(``);
    lines.push(`4. IMPORTANT INFORMATION`);
    if (Array.isArray(summary.important_information)) {
      summary.important_information.forEach((info) => lines.push(`• ${info}`));
    } else {
      lines.push(summary.important_information || 'N/A');
    }
    lines.push(``);
    lines.push(`5. TARGET AUDIENCE`);
    lines.push(summary.target_audience || 'N/A');
    lines.push(``);
    lines.push(`6. MAIN SERVICES OR PRODUCTS`);
    if (Array.isArray(summary.main_services_or_products)) {
      summary.main_services_or_products.forEach((s) => lines.push(`• ${s}`));
    } else {
      lines.push(summary.main_services_or_products || 'N/A');
    }
    lines.push(``);
    lines.push(`7. IMPORTANT KEYWORDS`);
    if (Array.isArray(summary.important_keywords)) {
      lines.push(summary.important_keywords.join(', '));
    } else {
      lines.push(summary.important_keywords || 'N/A');
    }
    lines.push(``);
    lines.push(`8. OVERALL CONCLUSION`);
    lines.push(summary.overall_conclusion || 'N/A');
    lines.push(``);
    lines.push(`=======================================================`);
    lines.push(`Generated by WebInsight - AI Website Summarizer`);
    lines.push(`=======================================================`);
    return lines.join('\n');
  };

  const handleCopy = () => {
    const text = buildSummaryText();
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const text = buildSummaryText();
    const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    const safeDomain = (metadata.domain || 'website').replace(/[^a-z0-9]/gi, '_').toLowerCase();
    link.href = url;
    link.download = `webinsight-${safeDomain}-summary.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="w-full max-w-6xl mx-auto py-8 px-4 sm:px-6 animate-fadeIn">
      
      {/* Top Header Card */}
      <div className="p-6 sm:p-8 rounded-3xl bg-white border border-slate-200/90 shadow-sm mb-8">
        <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-6">
          
          {/* Site identity */}
          <div className="flex items-start gap-4">
            <div className="w-14 h-14 rounded-2xl bg-slate-100 border border-slate-200/80 p-2 flex items-center justify-center flex-shrink-0 shadow-inner">
              {metadata.favicon ? (
                <img
                  src={metadata.favicon}
                  alt={metadata.domain}
                  className="w-9 h-9 rounded object-contain"
                  onError={(e) => {
                    e.currentTarget.style.display = 'none';
                  }}
                />
              ) : (
                <Globe className="w-7 h-7 text-indigo-600" />
              )}
            </div>

            <div>
              <div className="flex flex-wrap items-center gap-2 mb-1">
                <h1 className="text-xl sm:text-2xl font-bold text-slate-900 tracking-tight">
                  {metadata.title || metadata.domain}
                </h1>
              </div>

              {/* URL with external link */}
              <a
                href={metadata.url}
                target="_blank"
                rel="noopener noreferrer"
                className="inline-flex items-center gap-1.5 text-xs sm:text-sm font-medium text-indigo-600 hover:text-indigo-700 hover:underline break-all"
              >
                <span>{metadata.url}</span>
                <ExternalLink className="w-3.5 h-3.5 flex-shrink-0" />
              </a>

              {/* Metadata Badges */}
              <div className="flex flex-wrap items-center gap-2 mt-3 text-xs text-slate-500">
                <span className="inline-flex items-center gap-1 px-2.5 py-1 rounded-md bg-slate-100 font-medium text-slate-700">
                  <BookOpen className="w-3.5 h-3.5 text-slate-400" />
                  {metadata.word_count?.toLocaleString() || 0} words extracted
                </span>
                <span className="inline-flex items-center gap-1 px-2.5 py-1 rounded-md bg-slate-100 font-medium text-slate-700">
                  <Clock className="w-3.5 h-3.5 text-slate-400" />
                  ~{metadata.reading_time_minutes || 1} min read
                </span>
                <span className="inline-flex items-center gap-1 px-2.5 py-1 rounded-md bg-indigo-50 font-medium text-indigo-700 border border-indigo-100">
                  <Sparkles className="w-3.5 h-3.5 text-indigo-500" />
                  {summary._model_used || 'WebInsight AI Engine'}
                </span>
              </div>
            </div>
          </div>

          {/* Action buttons */}
          <div className="flex flex-wrap items-center gap-2.5 sm:self-end lg:self-center">
            <button
              onClick={handleCopy}
              className="inline-flex items-center gap-2 px-4 py-2.5 rounded-xl text-xs sm:text-sm font-semibold text-slate-700 bg-white hover:bg-slate-50 border border-slate-200/90 shadow-sm hover:border-slate-300 transition-all active:scale-[0.98]"
            >
              {copied ? (
                <>
                  <Check className="w-4 h-4 text-emerald-600" />
                  <span className="text-emerald-700">Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-4 h-4 text-slate-500" />
                  <span>Copy Summary</span>
                </>
              )}
            </button>

            <button
              onClick={handleDownload}
              className="inline-flex items-center gap-2 px-4 py-2.5 rounded-xl text-xs sm:text-sm font-semibold text-slate-700 bg-white hover:bg-slate-50 border border-slate-200/90 shadow-sm hover:border-slate-300 transition-all active:scale-[0.98]"
            >
              <Download className="w-4 h-4 text-slate-500" />
              <span>Download TXT</span>
            </button>

            <button
              onClick={onReset}
              className="inline-flex items-center gap-2 px-4 py-2.5 rounded-xl text-xs sm:text-sm font-semibold text-white bg-slate-900 hover:bg-slate-800 shadow-sm transition-all active:scale-[0.98]"
            >
              <RefreshCw className="w-4 h-4" />
              <span>Analyze Another</span>
            </button>
          </div>
        </div>
      </div>

      {/* 8 Structured Summary Sections Grid */}
      <div className="space-y-6">

        {/* Section 1: Overview & Section 2: Main Purpose (Two Columns) */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
          <SummaryCard
            icon={Compass}
            title="1. Website Overview"
            accent="indigo"
            badge="Executive Snapshot"
          >
            <p className="text-slate-700 text-sm sm:text-base leading-relaxed">
              {summary.website_overview || 'No overview provided.'}
            </p>
          </SummaryCard>

          <SummaryCard
            icon={Target}
            title="2. Main Purpose"
            accent="violet"
            badge="Core Mission"
          >
            <p className="text-slate-700 text-sm sm:text-base leading-relaxed">
              {summary.main_purpose || 'No purpose statement available.'}
            </p>
          </SummaryCard>
        </div>

        {/* Section 3: Key Features & Section 4: Important Information */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
          <SummaryCard
            icon={Sparkles}
            title="3. Key Features"
            accent="emerald"
            badge="Capabilities"
          >
            {Array.isArray(summary.key_features) && summary.key_features.length > 0 ? (
              <ul className="space-y-2.5">
                {summary.key_features.map((feature, idx) => (
                  <li key={idx} className="flex items-start gap-2.5 text-xs sm:text-sm text-slate-700">
                    <span className="w-5 h-5 rounded-full bg-emerald-50 text-emerald-600 flex items-center justify-center flex-shrink-0 mt-0.5 text-xs font-bold">
                      ✓
                    </span>
                    <span className="leading-relaxed">{feature}</span>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="text-sm text-slate-500 italic">No explicit features listed.</p>
            )}
          </SummaryCard>

          <SummaryCard
            icon={Info}
            title="4. Important Information"
            accent="amber"
            badge="Key Facts & Policies"
          >
            {Array.isArray(summary.important_information) && summary.important_information.length > 0 ? (
              <ul className="space-y-2.5">
                {summary.important_information.map((item, idx) => (
                  <li key={idx} className="flex items-start gap-2.5 text-xs sm:text-sm text-slate-700">
                    <span className="w-5 h-5 rounded-full bg-amber-50 text-amber-600 flex items-center justify-center flex-shrink-0 mt-0.5 text-xs font-bold">
                      •
                    </span>
                    <span className="leading-relaxed">{item}</span>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="text-sm text-slate-500 italic">No specific caveats or facts specified.</p>
            )}
          </SummaryCard>
        </div>

        {/* Section 5: Target Audience & Section 6: Main Services or Products */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
          <SummaryCard
            icon={Users}
            title="5. Target Audience"
            accent="blue"
            badge="Ideal Persona"
          >
            <p className="text-slate-700 text-xs sm:text-sm leading-relaxed">
              {summary.target_audience || 'Audience not specified.'}
            </p>
          </SummaryCard>

          <SummaryCard
            icon={Briefcase}
            title="6. Main Services or Products"
            accent="teal"
            badge="Offerings"
          >
            {Array.isArray(summary.main_services_or_products) && summary.main_services_or_products.length > 0 ? (
              <ul className="space-y-2">
                {summary.main_services_or_products.map((item, idx) => (
                  <li key={idx} className="flex items-start gap-2 text-xs sm:text-sm text-slate-700">
                    <span className="text-teal-600 font-bold">•</span>
                    <span>{item}</span>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="text-slate-700 text-xs sm:text-sm leading-relaxed">
                {summary.main_services_or_products || 'Information not specified.'}
              </p>
            )}
          </SummaryCard>
        </div>

        {/* Section 7: Important Keywords & Section 8: Overall Conclusion */}
        <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
          <SummaryCard
            icon={Key}
            title="7. Important Keywords"
            accent="purple"
            className="md:col-span-1"
            badge="Taxonomy"
          >
            <KeywordsCloud keywords={summary.important_keywords} />
          </SummaryCard>

          <SummaryCard
            icon={FileCheck2}
            title="8. Overall Conclusion"
            accent="indigo"
            className="md:col-span-2"
            badge="Executive Verdict"
          >
            <p className="text-slate-800 text-sm sm:text-base leading-relaxed font-normal">
              {summary.overall_conclusion || 'No concluding remarks provided.'}
            </p>
          </SummaryCard>
        </div>

      </div>

      {/* Section D: AI Website Q&A ("Ask This Website") */}
      <AskWebsiteQA
        sessionId={session_id}
        domain={metadata.domain || 'this website'}
        title={metadata.title || ''}
      />

    </div>
  );
}
